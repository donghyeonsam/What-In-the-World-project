-- ============================================================================
-- witw 쓰기 비용 측정
--
-- 목적: 인덱스를 추가했을 때 INSERT 가 얼마나 느려지는지 재는 것.
-- 실행: docker exec witw-postgres-perf psql -U postgres -d witw -f /tmp/write-test.sql
--
-- ---------------------------------------------------------------------------
-- 왜 필요한가
-- ---------------------------------------------------------------------------
-- 이 프로젝트는 Kafka 컨슈머가 article 을 계속 INSERT 합니다
-- (DbWriterService.saveAll). 인덱스를 하나 만들 때마다 INSERT 는 그 인덱스를
-- 갱신해야 하므로 느려집니다.
--
-- measure.sql 로 읽기만 재고 인덱스를 늘리면, 대시보드는 빨라지는데 수집
-- 파이프라인이 밀리는 상황을 못 봅니다. 인덱스 채택 여부는 읽기 개선과
-- 쓰기 저하를 같이 놓고 판단해야 합니다.
--
-- ---------------------------------------------------------------------------
-- 측정 방법
-- ---------------------------------------------------------------------------
-- 1. 인덱스를 만들기 "전" 에 한 번 돌려서 기준값을 잡습니다.
-- 2. 인덱스를 하나 만들고 다시 돌립니다.
-- 3. Execution Time 을 비교합니다. 저하가 10% 를 넘으면 채택 재검토.
--
-- measure.sql 과 마찬가지로 3회 이상 돌리고 마지막 값을 씁니다.
--
-- ---------------------------------------------------------------------------
-- 주의
-- ---------------------------------------------------------------------------
-- * 삽입한 행은 맨 끝에서 전부 지우고 VACUUM ANALYZE 까지 합니다. 따라서
--   이 스크립트를 돌려도 measure.sql 의 읽기 측정 조건은 그대로 유지됩니다.
-- * id 접두어가 'wtest-' 라서 generate-bulk.sql 의 'perf-' 데이터와 섞이지
--   않습니다. 중간에 실패해도 아래 한 줄로 정리할 수 있습니다.
--     DELETE FROM article WHERE id LIKE 'wtest-%';
-- * 이것은 대량 INSERT 라서 Hibernate 의 건별 INSERT 와 형태가 다릅니다.
--   절대 시간을 운영 수치로 읽지 마시고, 인덱스 유무에 따른 "배수" 로만
--   해석하십시오. 측정 대상은 인덱스 유지 비용입니다.
-- ============================================================================


-- ############################################################################
-- 0. 연결 대상 가드
--
-- 이 스크립트는 article 에 1만 건을 INSERT 합니다 (측정 후 삭제하지만
-- 실데이터 DB 에서 돌릴 이유가 없습니다). perf 데이터셋이 아니면 멈춥니다.
-- ############################################################################

DO $guard$
DECLARE
    perfrow bigint;
BEGIN
    SELECT count(*) INTO perfrow FROM article WHERE id LIKE 'perf-%';
    IF perfrow = 0 THEN
        RAISE EXCEPTION
            'perf 데이터셋이 아닙니다. 연결 대상을 확인하십시오 (perf 컨테이너는 포트 15432).';
    END IF;
END
$guard$;



-- ----------------------------------------------------------------------------
-- 사전 정리: 이전 실행이 중간에 죽었을 경우를 대비
-- ----------------------------------------------------------------------------
DELETE FROM article WHERE id LIKE 'wtest-%';


-- ----------------------------------------------------------------------------
-- 현재 article 인덱스 목록 — 결과를 기록할 때 같이 적으십시오.
-- ----------------------------------------------------------------------------
SELECT indexname, indexdef
FROM pg_indexes
WHERE schemaname = 'public' AND tablename = 'article'
ORDER BY indexname;


-- ----------------------------------------------------------------------------
-- 측정: 1만 건 INSERT
--
-- EXPLAIN ANALYZE 는 INSERT 를 실제로 실행하면서 시간을 찍어줍니다.
-- psql 메타명령(\timing)을 쓰지 않으므로 pgAdmin 에서도 동작합니다.
--
-- 본문 길이를 운영과 비슷하게 채웁니다. 짧은 더미로 넣으면 페이지당 행 수가
-- 많아져서 쓰기 비용이 실제보다 작게 나옵니다.
-- ----------------------------------------------------------------------------
EXPLAIN (ANALYZE, BUFFERS, TIMING OFF, COSTS OFF)
INSERT INTO article (id, publisher_country_code, theme_id, issue_id, publisher, url,
                     original_title, translated_title, crawled_at, theme_relevance_score,
                     issue_similarity, tone_score, summary, created_at, published_at)
SELECT 'wtest-' || g,
       'A0',
       1 + (g % 68),
       1 + (g % 200),
       'WriteTest',
       'https://example.test/' || g,
       repeat('t', 80),
       repeat('k', 80),
       CURRENT_TIMESTAMP,
       0.5,
       0.5,
       0.1,
       repeat('s', 300),
       CURRENT_TIMESTAMP,
       CURRENT_TIMESTAMP
FROM generate_series(1, 10000) g;


-- ----------------------------------------------------------------------------
-- 정리: 측정용 행을 지우고 통계를 원상 복구합니다.
-- 이걸 빼먹으면 이후 measure.sql 결과가 베이스라인과 비교 불가능해집니다.
-- ----------------------------------------------------------------------------
DELETE FROM article WHERE id LIKE 'wtest-%';

VACUUM ANALYZE article;
