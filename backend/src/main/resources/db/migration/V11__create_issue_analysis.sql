-- 국가가 해당 이슈를 어떻게 생각하는지 테이블
CREATE TABLE issue_country_analysis (
               id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
         issue_id BIGINT NOT NULL,
     country_code VARCHAR(2) NOT NULL,
            title TEXT NOT NULL,
          summary TEXT NOT NULL,
          details TEXT NOT NULL,
    article_count INTEGER NOT NULL,
       created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_issue_country_analysis PRIMARY KEY(id),
    CONSTRAINT fk_issue_country_analysis_issue
        FOREIGN KEY (issue_id) REFERENCES issue (id) ON DELETE CASCADE,
    CONSTRAINT fk_issue_country_analysis_country
        FOREIGN KEY (country_code) REFERENCES country (country_code) ON DELETE CASCADE,

    CONSTRAINT uq_issue_country_analysis_window
        UNIQUE (issue_id, country_code, created_at)
);


-- 분석에 쓰인 기사들 1:N 관계 테이블
CREATE TABLE issue_country_analysis_evidence (
    analysis_id BIGINT NOT NULL,
     article_id VARCHAR(255) NOT NULL,

    CONSTRAINT pk_issue_country_analysis_evidence
        PRIMARY KEY (analysis_id, article_id),
    CONSTRAINT fk_issue_country_analysis_evidence_analysis
        FOREIGN KEY (analysis_id) REFERENCES issue_country_analysis (id) ON DELETE CASCADE,
    CONSTRAINT fk_issue_country_analysis_evidence_article
        FOREIGN KEY (article_id) REFERENCES article (id) ON DELETE CASCADE
);