-- 사용자 전체 알림 설정
CREATE TABLE notification_setting (

    user_id         BIGINT  NOT NULL,
    enabled         BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT pk_notification_setting PRIMARY KEY (user_id),

    CONSTRAINT fk_notification_setting_user
        FOREIGN KEY (user_id) REFERENCES users (id)
);

-- 사용자별 테마 새 기사 알림
CREATE TABLE notification (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    user_id         BIGINT       NOT NULL,
    theme_id        BIGINT       NOT NULL,
    title           VARCHAR(255) NOT NULL,
    message         TEXT         NOT NULL,
    article_count   INTEGER      NOT NULL,
    period_start    TIMESTAMP    NOT NULL,
    period_end      TIMESTAMP    NOT NULL,
    created_at      TIMESTAMP    NOT NULL
        DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Seoul'),
    read_at         TIMESTAMP    NULL,
    deleted_at      TIMESTAMP    NULL,

    CONSTRAINT pk_notification PRIMARY KEY (id),

    CONSTRAINT fk_notification_user
        FOREIGN KEY (user_id) REFERENCES users (id),

    CONSTRAINT fk_notification_theme
        FOREIGN KEY (theme_id) REFERENCES theme (id),

    CONSTRAINT ck_notification_article_count
        CHECK (article_count > 0),

    CONSTRAINT ck_notification_period
        CHECK (period_start < period_end),

    CONSTRAINT uk_notification_user_theme_period
        UNIQUE (user_id, theme_id, period_start, period_end)
);

-- 삭제하지 않은 알림 목록을 최신순으로 조회
CREATE INDEX ix_notification_user_created
    ON notification (user_id, created_at DESC, id DESC)
    WHERE deleted_at IS NULL;

-- 삭제하지 않은 미읽음 알림 조회
CREATE INDEX ix_notification_user_unread
    ON notification (user_id)
    WHERE read_at IS NULL AND deleted_at IS NULL;