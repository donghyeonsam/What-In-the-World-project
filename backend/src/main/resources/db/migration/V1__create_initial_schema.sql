

CREATE TABLE field (
                        id              BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
                        code            VARCHAR(50)     NOT NULL,
                        name            VARCHAR(100)    NOT NULL,
                        description     VARCHAR(255)    NOT NULL,
                        created_at      TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,

                        CONSTRAINT PK_FIELD PRIMARY KEY (id)
);


CREATE TABLE country (
                         country_code    VARCHAR(2)     NOT NULL,
                         name_ko         VARCHAR(50)    NOT NULL,
                         name_en         VARCHAR(50)    NOT NULL,

                         CONSTRAINT PK_COUNTRY PRIMARY KEY (country_code)
);


CREATE TABLE theme (
                       id              BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
                       field_id       BIGINT          NOT NULL,
                       code            VARCHAR(50)     NOT NULL,
                       name            VARCHAR(50)    NOT NULL,
                       description     VARCHAR(255)    NOT NULL,
                       embedding       TEXT            NULL,
                       created_at      TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
                       updated_at      TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,

                       CONSTRAINT PK_THEME PRIMARY KEY (id),
                       CONSTRAINT FK_FIELD_TO_THEME
                           FOREIGN KEY (field_id) REFERENCES field (id)
);


CREATE TABLE issue (
                       id              BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
                       theme_id        BIGINT          NOT NULL,
                       name            VARCHAR(50)    NOT NULL,
                       embedding       TEXT            NULL,
                       first_seen_at   TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
                       created_at      TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
                       updated_at      TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,

                       CONSTRAINT PK_ISSUE PRIMARY KEY (id),
                       CONSTRAINT FK_THEME_TO_ISSUE
                           FOREIGN KEY (theme_id) REFERENCES theme (id)
);


CREATE TABLE article (
                         id                          BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
                         publisher_country_code      VARCHAR(2)      NOT NULL,
                         theme_id                    BIGINT          NOT NULL,
                         issue_id                    BIGINT          NULL,
                         uuid                        UUID            NOT NULL,
                         publisher                   VARCHAR(255)    NOT NULL DEFAULT '정보없음',
                         url                         VARCHAR(1000)   NOT NULL,
                         original_title              TEXT            NOT NULL,
                         translated_title            TEXT            NULL,
                         crawled_at                  TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
                         theme_relevance_score       DECIMAL         NOT NULL,
                         embedding                   TEXT            NULL,
                         issue_similarity            DECIMAL         NOT NULL,
                         tone_score                  DECIMAL         NOT NULL,
                         summary                     TEXT            NULL,
                         created_at                  TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
                         published_at                TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
                         issue_assigned_at           TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
                         deleted_at                  TIMESTAMP       NULL,


                         CONSTRAINT PK_ARTICLE PRIMARY KEY (id),
                         CONSTRAINT FK_THEME_TO_ARTICLE
                             FOREIGN KEY (theme_id) REFERENCES theme (id),
                         CONSTRAINT FK_ISSUE_TO_ARTICLE
                             FOREIGN KEY (issue_id) REFERENCES issue (id),
                         CONSTRAINT FK_COUNTRY_TO_ARTICLE
                             FOREIGN KEY (publisher_country_code) REFERENCES country (country_code)
);


CREATE TABLE country_tone (
                              calculated_at   TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
                              issue_id        BIGINT          NOT NULL,
                              country_code    VARCHAR(2)      NOT NULL,
                              tone_avg        DECIMAL         NOT NULL,
                              tone_sd         DECIMAL         NOT NULL,
                              article_count   BIGINT          NOT NULL,

                              CONSTRAINT PK_COUNTRY_TONE
                                  PRIMARY KEY (calculated_at, issue_id, country_code),

                              CONSTRAINT FK_ISSUE_TO_COUNTRY_TONE
                                  FOREIGN KEY (issue_id) REFERENCES issue (id),

                              CONSTRAINT FK_COUNTRY_TO_COUNTRY_TONE
                                  FOREIGN KEY (country_code) REFERENCES country (country_code)
);


CREATE TABLE article_summary (
                                 id                      BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
                                 total_article_count     BIGINT          NOT NULL DEFAULT 0,
                                 today_article_count     BIGINT          NOT NULL DEFAULT 0,
                                 updated_at              TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                 CONSTRAINT PK_ARTICLE_SUMMARY PRIMARY KEY (id)
);


CREATE TABLE article_country_mention (
                                         article_id      BIGINT          NOT NULL,
                                         country_code    VARCHAR(2)      NOT NULL,
                                         uuid            UUID            NOT NULL,

                                         CONSTRAINT PK_ARTICLE_COUNTRY_MENTION
                                             PRIMARY KEY (article_id, country_code),

                                         CONSTRAINT FK_ARTICLE_TO_ARTICLE_COUNTRY_MENTION
                                             FOREIGN KEY (article_id) REFERENCES article (id),

                                         CONSTRAINT FK_COUNTRY_TO_ARTICLE_COUNTRY_MENTION
                                             FOREIGN KEY (country_code) REFERENCES country (country_code)
);

